<?php

namespace App\Services;

use App\Models\MobileOtp;
use Illuminate\Support\Facades\Hash;

class OtpService
{
    /*
    |--------------------------------------------------------------------------
    | Generate OTP
    |--------------------------------------------------------------------------
    */

    public function generate(
        string $mobile,
        string $purpose
    ): string {

        /*
        |--------------------------------------------------------------------------
        | Remove Previous Unused OTP
        |--------------------------------------------------------------------------
        */

        MobileOtp::where('mobile', $mobile)
            ->where('purpose', $purpose)
            ->whereNull('verified_at')
            ->delete();


        /*
        |--------------------------------------------------------------------------
        | Generate 6 Digit OTP
        |--------------------------------------------------------------------------
        */

        $otp = (string) random_int(100000, 999999);


        /*
        |--------------------------------------------------------------------------
        | Store Hashed OTP
        |--------------------------------------------------------------------------
        */

        MobileOtp::create([
            'mobile' => $mobile,
            'otp_hash' => Hash::make($otp),
            'purpose' => $purpose,
            'expires_at' => now()->addMinutes(5),
            'attempt_count' => 0,
        ]);


        /*
        |--------------------------------------------------------------------------
        | Return Plain OTP
        |--------------------------------------------------------------------------
        |
        | Plain OTP শুধু SMS service-এ পাঠানোর জন্য return করছি।
        | Database-এ plain OTP রাখা হচ্ছে না।
        |
        */

        return $otp;
    }


    /*
    |--------------------------------------------------------------------------
    | Verify OTP
    |--------------------------------------------------------------------------
    */

    public function verify(
        string $mobile,
        string $otp,
        string $purpose
    ): bool {

        /*
        |--------------------------------------------------------------------------
        | Get Latest Active OTP
        |--------------------------------------------------------------------------
        */

        $record = MobileOtp::where('mobile', $mobile)
            ->where('purpose', $purpose)
            ->whereNull('verified_at')
            ->latest('id')
            ->first();


        /*
        |--------------------------------------------------------------------------
        | OTP Not Found
        |--------------------------------------------------------------------------
        */

        if (!$record) {
            return false;
        }


        /*
        |--------------------------------------------------------------------------
        | OTP Expired
        |--------------------------------------------------------------------------
        */

        if ($record->expires_at->isPast()) {
            return false;
        }


        /*
        |--------------------------------------------------------------------------
        | Maximum Attempts
        |--------------------------------------------------------------------------
        */

        if ($record->attempt_count >= 5) {
            return false;
        }


        /*
        |--------------------------------------------------------------------------
        | Increase Attempt
        |--------------------------------------------------------------------------
        */

        $record->increment('attempt_count');

        $record->update([
            'last_attempt_at' => now(),
        ]);


        /*
        |--------------------------------------------------------------------------
        | Check Hashed OTP
        |--------------------------------------------------------------------------
        */

        if (!Hash::check($otp, $record->otp_hash)) {
            return false;
        }


        /*
        |--------------------------------------------------------------------------
        | Mark OTP Verified
        |--------------------------------------------------------------------------
        */

        $record->update([
            'verified_at' => now(),
        ]);


        return true;
    }
}